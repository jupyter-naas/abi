#!/usr/bin/env node
// @ts-check

/**
 * The Developer guide's index of the architecture decision records
 * (docs/adr/*.md at the repository root): docs/developer-guide/adr.md.
 *
 *   node scripts/adr-index.js           fail when the page is out of date
 *   node scripts/adr-index.js --write   regenerate it
 *
 * `npm run check:adr-index` runs the check; the docs workflow runs it. A new ADR
 * is listed by running `npm run adr-index` and committing the page.
 */

const fs = require("fs");
const path = require("path");

const ADR_DIR = path.join(__dirname, "..", "..", "adr");
const PAGE = path.join(__dirname, "..", "docs", "developer-guide", "adr.md");
const GITHUB = "https://github.com/jupyter-naas/abi/blob/main/docs/adr";

/** First match wins. Files that match none are listed under "Other". */
const GROUPS = [
  ["Deployment, releases and documentation", /dokploy|repository-runs|maintenance-branch|docs-user/],
  ["Nexus", /nexus|office|skills|orchestrator|local-code|people|personnel|module_graph|auth-signup|no-default|sysadmin/],
  ["Data, documents and events", /ducklake|document|dataset|event|activity|compaction/],
  ["NATS, modules and the kernel", /nats|module|sdk|discovery|remote|engine|kernel|claim|proto|jobs|observability|stop-on|concurrent|serving/],
];

function groupOf(file) {
  for (const [name, pattern] of GROUPS) if (pattern.test(file)) return name;
  return "Other";
}

function title(file) {
  const text = fs.readFileSync(path.join(ADR_DIR, file), "utf8");
  const heading = text.match(/^#\s+(.+)$/m);
  return heading ? heading[1].trim() : file.replace(/\.md$/, "");
}

function render() {
  const files = fs
    .readdirSync(ADR_DIR)
    .filter((f) => /^\d{8}_.+\.md$/.test(f))
    .sort();
  const byGroup = new Map();
  for (const file of files) {
    const name = groupOf(file);
    if (!byGroup.has(name)) byGroup.set(name, []);
    byGroup.get(name).push(file);
  }
  const order = [...GROUPS.map(([name]) => name), "Other"];
  const out = [
    "---",
    "sidebar_position: 8",
    'title: "Architecture decision records"',
    "---",
    "",
    "<!-- Generated by scripts/adr-index.js: run `npm run adr-index` in docs/site after adding an ADR. -->",
    "",
    "# Architecture decision records",
    "",
    `An ADR records a decision about a boundary, an ownership, cross-cutting configuration or a major trade-off: its context, the decision and its consequences. They live in [\`docs/adr/\`](${GITHUB.replace("/blob/", "/tree/")}), one file each, named \`YYYYMMDD_topic.md\`; add one when a change makes such a decision (see [Contribute to ABI](/developer-guide/contributing/overview#conventions)). ${files.length} are listed here, oldest first within a group.`,
    "",
  ];
  for (const name of order) {
    const list = byGroup.get(name);
    if (!list) continue;
    out.push(`## ${name}`, "");
    for (const file of list) {
      const date = `${file.slice(0, 4)}-${file.slice(4, 6)}-${file.slice(6, 8)}`;
      out.push(`- [${title(file)}](${GITHUB}/${file}) (${date})`);
    }
    out.push("");
  }
  return out.join("\n");
}

const expected = render();
if (process.argv.includes("--write")) {
  fs.writeFileSync(PAGE, expected);
  console.log(`Wrote ${path.relative(process.cwd(), PAGE)}`);
} else {
  const actual = fs.existsSync(PAGE) ? fs.readFileSync(PAGE, "utf8") : "";
  if (actual !== expected) {
    console.error("docs/developer-guide/adr.md is out of date with docs/adr: run `npm run adr-index`.");
    process.exit(1);
  }
  console.log("ADR index is up to date.");
}
