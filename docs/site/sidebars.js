/**
 * Two top sections, one sidebar each:
 *
 * - `userGuide`: people who build and run projects on ABI.
 * - `developerGuide`: people who work on ABI itself.
 *
 * Every hand-written page lives in exactly one of them. A section is a folder
 * of docs/ that a category below renders (sub-folders take their label and
 * order from their own `_category_.json`). The upgrade pages are the exception:
 * GitHub URLs of their files are linked from commits, CHANGELOGs and PyPI
 * READMEs, so they stay under docs/upgrade/ and get their place in the User
 * guide from here and from the `slug` in their front matter.
 */

/**
 * @param {string} label
 * @param {string} slug
 * @param {string} description
 * @param {string} dirName
 */
